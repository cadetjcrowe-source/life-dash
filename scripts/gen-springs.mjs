// Generates src/app/motion.css: SwiftUI-style springs as CSS linear() easings.
//
// SwiftUI defines springs by perceptual `duration` and `bounce`. Apple's Spring
// docs give: Spring(duration: 0.5, bounce: 0.3) == mass 1, stiffness 157.9, damping 17.6,
// which matches  stiffness = (2π / duration)²,  damping = 4π(1 − bounce) / duration.
// We simulate that spring (mass 1, 0 → 1) and sample it into a linear() curve.
// Usage: node scripts/gen-springs.mjs
import { writeFileSync } from "node:fs";

const SPRINGS = {
  // name: [duration, bounce]  – SwiftUI presets
  smooth: [0.5, 0], // Animation.smooth – no bounce (sheets, layout, progress)
  snappy: [0.5, 0.15], // Animation.snappy – small bounce (most UI changes)
  bouncy: [0.5, 0.3], // Animation.bouncy – playful (checkmarks, celebrations)
  interactive: [0.15, 0.14], // Animation.interactiveSpring – press feedback
  quick: [0.3, 0], // smooth(duration: 0.3) – small fades/toasts
};

function simulate(duration, bounce) {
  const k = (2 * Math.PI / duration) ** 2;
  const c = (4 * Math.PI * (1 - bounce)) / duration;
  const dt = 1 / 600;
  let x = 0, v = 0, t = 0;
  const pts = [[0, 0]];
  // run until settled (within 0.1% and nearly still)
  while (t < 3) {
    const a = -k * (x - 1) - c * v;
    v += a * dt;
    x += v * dt;
    t += dt;
    pts.push([t, x]);
    if (Math.abs(x - 1) < 0.001 && Math.abs(v) < 0.01) break;
  }
  return { settle: t, pts };
}

let css = `/* Generated by scripts/gen-springs.mjs — SwiftUI spring presets as CSS easings. */\n:root {\n`;
for (const [name, [d, b]] of Object.entries(SPRINGS)) {
  const { settle, pts } = simulate(d, b);
  const N = 48;
  const samples = [];
  for (let i = 0; i <= N; i++) {
    const target = (i / N) * settle;
    const p = pts.reduce((best, q) => (Math.abs(q[0] - target) < Math.abs(best[0] - target) ? q : best));
    samples.push(i === N ? "1" : (+p[1].toFixed(4)).toString());
  }
  css += `  /* .${name}: duration ${d}s, bounce ${b} → settles in ${settle.toFixed(2)}s */\n`;
  css += `  --spring-${name}: linear(${samples.join(", ")});\n`;
  css += `  --dur-${name}: ${Math.round(settle * 1000)}ms;\n`;
}
css += `}\n`;
writeFileSync(new URL("../src/app/motion.css", import.meta.url), css);
console.log(css);
